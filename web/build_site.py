#!/usr/bin/env python3
"""Assemble the GitHub Pages site in ``docs/``.

GitHub Pages for this repository is configured to publish ``main`` / ``/docs``,
so the browser build is assembled there rather than at the repository root.
``docs/`` is a build output: edit ``web/index.html``, then run this script.

What it produces:

``docs/index.html``      verbatim copy of ``web/index.html``
``docs/examples.js``     the example dataset embedded as JavaScript, so the
                         "load example" buttons need no further requests and
                         cannot drift from ``examples/``
``docs/<name>.whl``      the wheel the page imports via zipimport
``docs/.nojekyll``       tells Pages to serve the directory verbatim; without
                         it Jekyll rewrites the HTML and may drop the wheel

Usage::

    python web/build_site.py            # build
    python web/build_site.py --check    # fail if docs/ is out of date (CI)
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "web"
DOCS = ROOT / "docs"
EXAMPLES = ROOT / "examples"

#: Example files the page offers through its "load example" buttons.
BUNDLED = (
    "demogenea_locus.fa",
    "demogeneb_locus.fa",
    "demogenea_transcript.fa",
    "demogeneb_transcript.fa",
)

NOJEKYLL_NOTE = (
    "# Present so GitHub Pages serves this directory verbatim.\n"
    "# Jekyll would rewrite index.html and may not copy the .whl the page needs.\n"
)


def version() -> str:
    for line in (ROOT / "src" / "danioprime" / "__init__.py").read_text().splitlines():
        if line.startswith("__version__"):
            return line.split("=")[1].strip().strip("\"'")
    raise SystemExit("could not read __version__")


def wheel_path() -> Path:
    name = f"danioprime-{version()}-py3-none-any.whl"
    for candidate in (ROOT / name, DOCS / name):
        if candidate.exists():
            return candidate
    raise SystemExit(
        f"{name} not found. Build it with: python web/check_wheel.py --fix"
    )


def render_examples_js() -> str:
    data = {}
    for name in BUNDLED:
        path = EXAMPLES / name
        if not path.exists():
            raise SystemExit(f"missing example: {path.relative_to(ROOT)}")
        data[name] = path.read_text()
    body = json.dumps(data, indent=0, sort_keys=True)
    return (
        "// Generated by web/build_site.py from examples/ -- do not edit.\n"
        "// Embedded rather than fetched so the demo needs no extra requests\n"
        "// and cannot drift from the dataset the repository ships.\n"
        f"globalThis.DP_EXAMPLES = {body};\n"
    )


def planned_files() -> dict[str, bytes]:
    """Path relative to docs/ -> exact bytes it should contain."""
    wheel = wheel_path()
    return {
        "index.html": (WEB / "index.html").read_bytes(),
        "examples.js": render_examples_js().encode(),
        wheel.name: wheel.read_bytes(),
        ".nojekyll": NOJEKYLL_NOTE.encode(),
    }


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()[:12]


def build() -> int:
    DOCS.mkdir(exist_ok=True)
    plan = planned_files()
    # Remove wheels for other versions so the directory never serves two.
    for stale in DOCS.glob("danioprime-*.whl"):
        if stale.name not in plan:
            stale.unlink()
            print(f"removed stale {stale.name}")
    for name, data in plan.items():
        target = DOCS / name
        if target.exists() and target.read_bytes() == data:
            continue
        target.write_bytes(data)
        print(f"wrote docs/{name} ({len(data):,} bytes, {digest(data)})")
    print(f"docs/ is up to date ({len(plan)} files)")
    return 0


def check() -> int:
    plan = planned_files()
    problems: list[str] = []
    for name, data in plan.items():
        target = DOCS / name
        if not target.exists():
            problems.append(f"docs/{name} is missing")
        elif target.read_bytes() != data:
            problems.append(
                f"docs/{name} is out of date "
                f"(has {digest(target.read_bytes())}, expected {digest(data)})"
            )
    for stale in DOCS.glob("danioprime-*.whl"):
        if stale.name not in plan:
            problems.append(f"docs/{stale.name} is a wheel for another version")
    if problems:
        print("FAIL the published site in docs/ is out of date")
        for p in problems:
            print(f"     - {p}")
        print("     fix: python web/build_site.py")
        return 1
    print(f"ok   docs/ matches web/index.html, examples/ and the wheel ({len(plan)} files)")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="verify without writing")
    args = ap.parse_args()
    return check() if args.check else build()


if __name__ == "__main__":
    raise SystemExit(main())
